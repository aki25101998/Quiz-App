/**
 * Get a career by its ID.
 */
export function getCareerById(id: string): Career | undefined {
  return careerDatabase.find(c => c.id === id);
}

/**
 * Get all unique career fields.
 */
export function getCareerFields(): string[] {
  return [...new Set(careerDatabase.map(c => c.field))];
}
